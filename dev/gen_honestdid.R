# Regenerates R/vendor_honestdid.R from the installed HonestDiD package (run from the project root).
ns <- asNamespace("HonestDiD")
entries <- c("createSensitivityResults_relativeMagnitudes", "constructOriginalCS", "basisVector")
seen <- character(); todo <- entries
while (length(todo)) {
    f <- todo[1]; todo <- todo[-1]
    if (f %in% seen || !exists(f, ns, inherits = FALSE)) next
    fn <- get(f, ns); if (!is.function(fn)) next
    seen <- c(seen, f)
    todo <- c(todo, intersect(unique(all.names(body(fn))), ls(ns, all.names = TRUE)))
}
seen <- sort(seen)
hdr <- c("# Vendored from the 'HonestDiD' package (Ashesh Rambachan and Jonathan Roth), MIT licence,",
"# Copyright (c) 2021 HonestDiD authors. Only the code reachable from the relative-magnitudes",
"# sensitivity analysis (createSensitivityResults_relativeMagnitudes) and the original confidence",
"# set (constructOriginalCS) is included, with function names prefixed 'hd_' to avoid clashes.",
"# Reason: HonestDiD imports CVXR, which pulls in gmp, clarabel (Rust), highs (CMake), osqp, scs and",
"# ECOSolveR; the code below does not use them. Generated by dev/gen_honestdid.R from HonestDiD,",
"# verified by dev/test_honestdid.R (identical results). Not hand-edited.", "")
ren <- function(txt) {
    for (f in seen) {
        pat <- paste0("(?<![A-Za-z0-9._])", gsub(".", "[.]", f, fixed = TRUE), "(?![A-Za-z0-9._])")
        txt <- gsub(pat, paste0("hd_", f), txt, perl = TRUE)
    }
    txt
}
out <- hdr
for (f in seen) {
    fn <- get(f, ns); environment(fn) <- globalenv(); attr(fn, "srcref") <- NULL
    out <- c(out, paste0(f, " <- ", paste(deparse(fn, width.cutoff = 100L), collapse = "\n")), "")
}
out <- c(out, "`%do%` <- foreach::`%do%`", "`%dopar%` <- foreach::`%dopar%`", "")
writeLines(ren(paste(out, collapse = "\n")), "R/vendor_honestdid.R")
cat(length(seen), "functions\n")
