for idx, code in enumerate(['ja', 'zh_Hans']):
    path = os.path.join(root, code + '.po')
    s = open(path, encoding='utf-8').read()
    missing = []
    def fill(m):
        mid = m.group(1)
        if mid and mid in T:
            return 'msgid "%s"\nmsgstr "%s"' % (mid, T[mid][idx])
        if mid:
            missing.append(mid)
        return m.group(0)
    s = re.sub(r'msgid "((?:[^"\\]|\\.)*)"\nmsgstr "[^"]*"', fill, s)
    open(path, 'w', encoding='utf-8').write(s)
    print(code, 'missing translations:', missing)
