# Core layer: R code that reproduces the extended TWFE analysis with the public package etwfe (the module itself has its own implementation
# of the same regression because etwfe cannot run inside jamovi's formula sandbox).

dc_code_etwfe <- function(o, info) {
    q <- function(x) paste(deparse(x), collapse = "")
    covs <- o$covs
    indicator <- identical(o$treatType, "indicator")
    L <- character()
    add <- function(...) L <<- c(L, paste0(...))
    add("# ---------------------------------------------------------------------------")
    add("# Reproducible R code generated by the jamovi module 'didfamily'.")
    add("# Extended two-way fixed effects (Wooldridge) with the package etwfe.")
    add("# ---------------------------------------------------------------------------")
    add("library(etwfe)")
    add("")
    add("dat <- read.csv(\"your_data.csv\")   # <- one row per unit and period")
    add("")
    if (indicator) {
        add("## The cohort (first treated period) from the 0/1 treatment indicator; 0 = never treated")
        add("first <- tapply(ifelse(dat[[", q(o$treat), "]] == 1, dat[[", q(o$time), "]], Inf), dat[[", q(o$id), "]], min)")
        add("dat$first_treat <- ifelse(is.finite(first[as.character(dat[[", q(o$id), "]])]), first[as.character(dat[[", q(o$id), "]])], 0)")
        gv <- "first_treat"
    } else gv <- o$treat
    fml <- if (length(covs)) paste(o$dep, "~", paste(covs, collapse = " + ")) else paste(o$dep, "~ 0")
    fam <- switch(o$family, gaussian = "NULL", poisson = "\"poisson\"", logit = "\"logit\"")
    add("mod <- etwfe(")
    add("    fml = ", fml, ",")
    add("    tvar = ", o$time, ", gvar = ", gv, ", data = dat, gref = 0,")
    add("    cgroup = ", if (identical(o$control, "nevertreated")) "\"never\"" else "\"notyet\"", ", family = ", fam, ",")
    add("    vcov = ~", if (length(o$cluster)) o$cluster else o$id, ")")
    add("")
    add("emfx(mod, type = \"simple\")                                                          # overall effect on the treated")
    add("emfx(mod, type = \"event\", post_only = ", if (identical(o$control, "nevertreated")) "FALSE" else "TRUE", ")      # effects by event time")
    add("emfx(mod, type = \"group\")                                                           # by cohort")
    add("emfx(mod, type = \"calendar\")                                                        # by calendar time")
    paste(L, collapse = "\n")
}
