# Core layer: generates a standalone R script that reproduces the comparison with the public
# package functions (fixest, did, didimputation, did2s). The script runs in ordinary R; it uses
# sunab() and i() freely, which jamovi's formula validator blocks inside the module (the module
# implements Sun-Abraham itself, with identical results).

dc_q <- function(x) paste(deparse(x), collapse = "")

# `o`: list of module options; `info`: d$info from dc_prepare
dc_code_compare <- function(o, info) {
    covs <- info$covs
    ncov <- if (is.null(covs)) 0L else nrow(covs)
    cov_all <- if (ncov) paste(covs$code, collapse = " + ") else NULL
    cov_fe  <- if (ncov && any(covs$varying)) paste(covs$code[covs$varying], collapse = " + ") else NULL
    plus <- function(x) if (is.null(x)) "" else paste0(" + ", x)
    indicator <- identical(o$treatType, "indicator")
    cl <- !is.null(o$cluster) && length(o$cluster)
    weighted <- isTRUE(info$weighted)
    wt <- if (weighted) ", weights = dc$dc_sw" else ""          # weights argument of the fixest calls
    wst <- if (weighted) ", weights = st$dc_sw" else ""
    wcs <- if (weighted) ", weightsname = \"dc_sw\"" else ""
    wd2 <- if (weighted) ", weights = \"dc_sw\"" else ""
    use_bjs <- isTRUE(o$bjs) && !weighted
    L <- character()
    add <- function(...) L <<- c(L, paste0(...))

    add("# ---------------------------------------------------------------------------")
    add("# Reproducible R code generated by the jamovi module 'didfamily'.")
    add("# Replace `dat` with your data (one row per unit and period).")
    add("# ---------------------------------------------------------------------------")
    pk <- c("fixest", if (o$cs) "did", if (use_bjs) "didimputation", if (o$gardner) "did2s")
    for (p in unique(pk)) add("library(", p, ")")
    add("")
    add("dat <- read.csv(\"your_data.csv\")   # <- your data")
    add("")
    add("## 1. Prepare the panel (the same steps the module performs)")
    add("dc <- data.frame(")
    add("    dc_y   = as.numeric(as.character(dat[[", dc_q(o$dep), "]])),")
    add("    dc_id  = as.character(dat[[", dc_q(o$id), "]]),")
    add("    dc_t   = as.numeric(as.character(dat[[", dc_q(o$time), "]])),")
    extra <- c(if (cl) paste0("    dc_clraw = as.character(dat[[", dc_q(o$cluster), "]])"),
               if (weighted) paste0("    dc_sw = as.numeric(as.character(dat[[", dc_q(o$weights), "]]))"))
    add("    dc_raw = as.numeric(as.character(dat[[", dc_q(o$treat), "]]))", if (length(extra)) "," else ")")
    for (k in seq_along(extra)) add(extra[k], if (k < length(extra)) "," else ")")
    if (ncov) {
        for (i in seq_len(ncov)) {
            if (is.na(covs$level[i]))
                add("dc$", covs$code[i], " <- as.numeric(as.character(dat[[", dc_q(covs$var[i]), "]]))   # ", covs$label[i])
            else
                add("dc$", covs$code[i], " <- as.numeric(as.character(dat[[", dc_q(covs$var[i]), "]]) == ", dc_q(covs$level[i]), ")   # ", covs$label[i])
        }
    }
    need <- c("dc_y", "dc_id", "dc_t", if (cl) "dc_clraw", if (weighted) "dc_sw", if (ncov) covs$code, if (indicator) "dc_raw")
    add("dc <- dc[complete.cases(dc[, ", dc_q(need), "]), ]   # rows with missing values are dropped")
    add("dc$dc_id <- match(dc$dc_id, unique(dc$dc_id))")
    if (cl) add("dc$dc_cl <- match(dc$dc_clraw, unique(dc$dc_clraw))   # must be constant within unit")
    else add("dc$dc_cl <- dc$dc_id                                  # cluster at the unit level")
    add("dc <- dc[order(dc$dc_id, dc$dc_t), ]")
    tm <- info$time_map
    shifted <- !is.null(tm) && isTRUE(tm$shifted)
    if (shifted) {
        add("# periods are recoded to 1, 2, 3, ... (they start at <= 0 or are equally spaced by more than 1)")
        add("dc$dc_t <- (dc$dc_t - ", format(tm$t0, digits = 15), ") / ", format(tm$step, digits = 15), " + 1")
    }
    if (indicator) {
        add("first <- ave(ifelse(dc$dc_raw == 1, dc$dc_t, Inf), dc$dc_id, FUN = min)")
        add("dc$dc_g <- ifelse(is.infinite(first), 0, first)   # first treated period, 0 = never treated")
    } else {
        add("dc$dc_g <- dc$dc_raw")
        add("dc$dc_g[is.na(dc$dc_g) | is.infinite(dc$dc_g)] <- 0   # first treated period, 0 = never treated")
        if (shifted)
            add("pos <- dc$dc_g > 0; dc$dc_g[pos] <- pmax((dc$dc_g[pos] - ", format(tm$t0, digits = 15), ") / ", format(tm$step, digits = 15), " + 1, 1)")
    }
    add("dc$dc_g[dc$dc_g > max(dc$dc_t)] <- 0                    # treated only after the sample ends")
    add("dc <- dc[!(dc$dc_g > 0 & dc$dc_g <= min(dc$dc_t)), ]    # treated in the first period: no pre-period")
    add("dc$dc_d   <- as.integer(dc$dc_g > 0 & dc$dc_t >= dc$dc_g)")
    add("dc$dc_rel <- ifelse(dc$dc_g > 0, dc$dc_t - dc$dc_g, -1000)   # event time")
    add("")

    min_e <- o$minE; max_e <- o$maxE
    sumrows <- character()

    if (o$twfe) {
        add("## TWFE (static and event study)")
        add("twfe    <- feols(dc_y ~ dc_d", plus(cov_fe), " | dc_id + dc_t, data = dc", wt, ", vcov = ~dc_cl)")
        add("twfe_es <- feols(dc_y ~ i(dc_rel, ref = c(-1, -1000))", plus(cov_fe), " | dc_id + dc_t, data = dc", wt, ", vcov = ~dc_cl)")
        add("# iplot(twfe_es, xlim = c(", min_e, ", ", max_e, "))")
        add("")
        sumrows <- c(sumrows, "data.frame(estimator = \"TWFE\", att = coef(twfe)[[\"dc_d\"]], se = se(twfe)[[\"dc_d\"]])")
    }
    if (o$cs) {
        add("## Callaway & Sant'Anna")
        add("# the module runs did on units observed in every period")
        add("n_per <- length(unique(dc$dc_t)); cnt <- table(dc$dc_id)")
        add("dcb <- dc[dc$dc_id %in% as.integer(names(cnt)[cnt == n_per]), ]")
        use_boot <- isTRUE(o$boot) || isTRUE(info$cluster)
        if (use_boot) add("set.seed(", o$seed, ")")
        add("cs <- att_gt(yname = \"dc_y\", tname = \"dc_t\", idname = \"dc_id\", gname = \"dc_g\",")
        add("             xformla = ", if (is.null(cov_all)) "~1" else paste0("~ ", cov_all), ", data = dcb,")
        add("             control_group = ", dc_q(o$csControl), ", est_method = ", dc_q(o$csMethod), wcs, ",")
        add("             base_period = \"universal\", bstrap = ", use_boot, ", biters = ", o$bootReps,
            if (isTRUE(info$cluster)) ", clustervars = \"dc_cl\"" else "", ", cband = FALSE)")
        sd <- if (use_boot) paste0("set.seed(", o$seed, "); ") else ""   # the module reseeds before every aggregation
        ag <- paste0("bstrap = ", use_boot, ", biters = ", o$bootReps, if (isTRUE(info$cluster)) ", clustervars = \"dc_cl\"" else "", ", cband = FALSE")
        add(sd, "cs_overall <- aggte(cs, type = \"simple\", ", ag, ")")
        add(sd, "cs_es      <- aggte(cs, type = \"dynamic\", min_e = ", min_e, ", max_e = ", max_e, ", ", ag, ")")
        add(sd, "cs_group   <- aggte(cs, type = \"group\", ", ag, ")")
        add(sd, "cs_cal     <- aggte(cs, type = \"calendar\", ", ag, ")")
        add("# ggdid(cs_es)")
        add("")
        sumrows <- c(sumrows, "data.frame(estimator = \"Callaway-Sant'Anna\", att = cs_overall$overall.att, se = cs_overall$overall.se)")
    }
    if (o$sa) {
        add("## Sun & Abraham (never-treated units as controls)")
        add("dc$dc_gs <- ifelse(dc$dc_g > 0, dc$dc_g, 10000)")
        add("sa <- feols(dc_y ~ sunab(dc_gs, dc_t, ref.p = -1)", plus(cov_fe), " | dc_id + dc_t, data = dc", wt, ", vcov = ~dc_cl)")
        add("sa_att <- summary(sa, agg = \"att\")$coeftable   # overall ATT; summary(sa) gives the event-time effects")
        add("")
        sumrows <- c(sumrows, "data.frame(estimator = \"Sun-Abraham\", att = sa_att[1, 1], se = sa_att[1, 2])")
    }
    if (isTRUE(o$bjs) && weighted)
        add("## Borusyak, Jaravel & Spiess: skipped (didimputation has no sampling weights)\n")
    if (use_bjs) {
        add("## Borusyak, Jaravel & Spiess")
        fs <- if (is.null(cov_fe)) "" else paste0("first_stage = ~ ", cov_fe, " | dc_id + dc_t, ")
        add("bjs    <- did_imputation(yname = \"dc_y\", gname = \"dc_g\", tname = \"dc_t\", idname = \"dc_id\", data = dc,")
        add("                         ", fs, "cluster_var = \"dc_cl\")")
        add("bjs_es <- did_imputation(yname = \"dc_y\", gname = \"dc_g\", tname = \"dc_t\", idname = \"dc_id\", data = dc,")
        add("                         ", fs, "cluster_var = \"dc_cl\", horizon = 0:", max_e, ", pretrends = ", min_e, ":-2)")
        add("")
        sumrows <- c(sumrows, "data.frame(estimator = \"Borusyak-Jaravel-Spiess\", att = bjs$estimate[1], se = bjs$std.error[1])")
    }
    if (o$gardner) {
        add("## Gardner two-stage")
        fs <- paste0("~ ", if (is.null(cov_fe)) "0" else cov_fe, " | dc_id + dc_t")
        add("gardner    <- did2s(dc, yname = \"dc_y\", first_stage = ", fs, ", second_stage = ~ dc_d,")
        add("                    treatment = \"dc_d\", cluster_var = \"dc_cl\"", wd2, ")")
        add("gardner_es <- did2s(dc, yname = \"dc_y\", first_stage = ", fs, ",")
        add("                    second_stage = ~ i(dc_rel, ref = c(-1, -1000)), treatment = \"dc_d\", cluster_var = \"dc_cl\"", wd2, ")")
        add("")
        sumrows <- c(sumrows, "data.frame(estimator = \"Gardner (did2s)\", att = coeftable(gardner)[\"dc_d\", 1], se = coeftable(gardner)[\"dc_d\", 2])")
    }
    if (o$stacked) {
        add("## Stacked DiD (one sub-experiment per cohort, clean controls)")
        add("stacks <- lapply(sort(unique(dc$dc_g[dc$dc_g > 0])), function(g) {")
        add("    hi <- g + ", max_e)
        add("    w <- dc[dc$dc_t >= g + ", min_e, " & dc$dc_t <= hi, ]")
        add("    w <- w[w$dc_g == g | w$dc_g == 0 | w$dc_g > hi, ]")
        add("    if (!any(w$dc_g != g)) return(NULL)")
        add("    w$dc_trt <- as.numeric(w$dc_g == g); w$dc_erel <- w$dc_t - g")
        add("    w$dc_trtpost <- w$dc_trt * as.numeric(w$dc_erel >= 0); w$dc_stack <- g")
        add("    w")
        add("})")
        add("st <- do.call(rbind, Filter(Negate(is.null), stacks))")
        add("st$dc_ue <- paste(st$dc_id, st$dc_stack); st$dc_te <- paste(st$dc_t, st$dc_stack)")
        add("stacked    <- feols(dc_y ~ dc_trtpost", plus(cov_fe), " | dc_ue + dc_te, data = st", wst, ", vcov = ~dc_cl)")
        add("stacked_es <- feols(dc_y ~ i(dc_erel, dc_trt, ref = -1)", plus(cov_fe), " | dc_ue + dc_te, data = st", wst, ", vcov = ~dc_cl)")
        add("")
        sumrows <- c(sumrows, "data.frame(estimator = \"Stacked DiD\", att = coeftable(stacked)[\"dc_trtpost\", 1], se = coeftable(stacked)[\"dc_trtpost\", 2])")
    }
    if (length(sumrows)) {
        add("## Overall ATT by estimator")
        add("summary_table <- rbind(")
        add(paste0("    ", sumrows, collapse = ",\n"))
        add(")")
        add("print(summary_table)")
    }
    paste(L, collapse = "\n")
}
